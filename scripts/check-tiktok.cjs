    assert.equal(fs.readFileSync(artifact.filePath,'utf8'),'fixture-mp4-file');
    TikTokHttpClient.prototype.metadata=async()=>html;
    TikTokHttpClient.prototype.resolveUrl=async()=>photoUrl;
